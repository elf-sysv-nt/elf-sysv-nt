#!/usr/bin/env python3
"""Refresh doc/Next-Steps.md from git truth. Idempotent; safe to run every merge.

Three things, all mechanical:
  1. Regenerate the block between the LIVE-WORKTREES markers from `git worktree
     list` — each not-yet-merged branch, its state (BUILDING / STARTED-scaffold /
     committed-idle), and the WP it carries.
  2. Flip `WP-NN` to `WP-NN` with a check mark on the workstream chain lines (the
     indented lines with the arrow) for every work package the plan marks
     Delivered. Only chain lines are touched, so prose is never mangled.
  3. Stamp each `## ` section header with `  ·  updated YYYY-MM-DD HH:MM`, moving
     the time forward only when that section's body actually changed this run.

Run it from within the march worktree (its own bin/); it edits that worktree's
doc/Next-Steps.md. Commit the result and fast-forward main.
"""
import os, re, time, subprocess, datetime

HERE  = os.path.dirname(os.path.abspath(__file__))
ROOT  = os.path.dirname(HERE)                     # the worktree root
NS    = os.path.join(ROOT, 'doc', 'Next-Steps.md')
PLAN  = os.path.join(ROOT, 'doc', 'IMPLEMENTATION-PLAN.md')
NOW   = datetime.datetime.now().strftime('%Y-%m-%d %H:%M')
CHECK = '\u2713'                                   # ✓
STAMP = re.compile(r'\s*\u00b7\s*updated \d{4}-\d\d-\d\d \d\d:\d\d\s*$')


def git(args, cwd=ROOT):
    try:
        return subprocess.check_output(['git', '-C', cwd] + args,
                                       stderr=subprocess.DEVNULL).decode()
    except Exception:
        return ''


def delivered_wps():
    text = open(PLAN, encoding='utf-8', errors='replace').read()
    parts = re.split(r'(?m)^### (WP-\d+)\b', text)
    out = set()
    for i in range(1, len(parts), 2):
        if re.search(r'(?m)^(Delivered|Partial)\b', parts[i + 1]):
            out.add(parts[i])
    return out


def recent_files(path, secs=360):
    cutoff, n = time.time() - secs, 0
    for root, dirs, files in os.walk(path):
        if '.git' in root.replace('\\', '/').split('/'):
            dirs[:] = []
            continue
        for f in files:
            try:
                if os.path.getmtime(os.path.join(root, f)) > cutoff:
                    n += 1
            except OSError:
                pass
    return n


def worktree_block():
    mtip = git(['rev-parse', 'march']).strip()
    pairs, cur = [], None
    for line in git(['worktree', 'list', '--porcelain']).splitlines():
        if line.startswith('worktree '):
            cur = line[len('worktree '):]
        elif line.startswith('branch '):
            name = line[len('branch '):].rsplit('/', 1)[-1]
            if cur and name not in ('march', 'main'):
                pairs.append((name, cur))
    rows = []
    for name, wt in pairs:
        tip = git(['rev-parse', 'HEAD'], wt).strip()
        if not tip or tip == mtip:
            continue
        if subprocess.call(['git', '-C', wt, 'merge-base', '--is-ancestor', tip, mtip],
                           stderr=subprocess.DEVNULL) == 0:
            continue                                   # already merged
        ahead = (git(['rev-list', '--count', 'HEAD', '^march'], wt).strip() or '0')
        log = [l for l in git(['log', '--oneline', mtip + '..HEAD'], wt).splitlines() if l.strip()]
        scaffold_only = len(log) == 1 and 'scaffold' in log[0].lower()
        if recent_files(wt) > 0:
            st = 'BUILDING — %s commit(s), compiling now' % ahead
        elif scaffold_only:
            st = 'STARTED  — scaffold only, not built'
        elif int(ahead) > 0:
            st = 'committed %s — idle (check: done or stalled)' % ahead
        else:
            st = 'idle'
        m = re.match(r'wp(\d+)', name)
        wp = '(WP-%s)' % m.group(1) if m else ''
        rows.append('    %-22s %-44s %s' % (name, st, wp))
    if not rows:
        rows = ['    (none in flight — the queue is drained or the worker is between packages)']
    begin = '<!-- LIVE-WORKTREES:BEGIN (regenerated by bin/refresh-next-steps.py — do not hand-edit) -->'
    end = '<!-- LIVE-WORKTREES:END -->'
    return begin + '\n' + '\n'.join(rows) + '\n' + end


def flip_checks(text, delivered):
    def one(line):
        if '\u25ba' not in line and '->' not in line:   # only chain lines (arrow)
            return line
        def sub(m):
            wp = 'WP-' + m.group(1)
            return wp + CHECK if (wp in delivered and m.group(2) != CHECK) else m.group(0)
        return re.sub(r'WP-(\d+)(' + CHECK + r'?)', sub, line)
    return '\n'.join(one(l) for l in text.split('\n'))


def split_sections(text):
    """Return (preamble, [(header_line, body), ...]) split on '## ' lines."""
    lines = text.split('\n')
    pre, secs, i = [], [], 0
    while i < len(lines) and not lines[i].startswith('## '):
        pre.append(lines[i]); i += 1
    while i < len(lines):
        header = lines[i]; i += 1
        body = []
        while i < len(lines) and not lines[i].startswith('## '):
            body.append(lines[i]); i += 1
        secs.append((header, '\n'.join(body)))
    return '\n'.join(pre), secs


def main():
    old = open(NS, encoding='utf-8', errors='replace').read()
    delivered = delivered_wps()

    # capture the previous per-title timestamps and bodies (headers stripped of stamp)
    _, old_secs = split_sections(old)
    old_map = {}
    for h, b in old_secs:
        title = STAMP.sub('', h)
        m = STAMP.search(h)
        old_ts = re.search(r'updated (.*?)\s*$', m.group(0)).group(1) if m else None
        old_map[title] = (b, old_ts)

    # apply the mechanical edits
    new = re.sub(r'<!-- LIVE-WORKTREES:BEGIN.*?LIVE-WORKTREES:END -->',
                 lambda _: worktree_block(), old, flags=re.S)
    new = flip_checks(new, delivered)

    # restamp headers: bump time only where the body changed
    pre, new_secs = split_sections(new)
    rebuilt = [pre] if pre else []
    for h, b in new_secs:
        title = STAMP.sub('', h)
        old_b, old_ts = old_map.get(title, (None, None))
        ts = NOW if (old_b is None or old_b != b) else old_ts or NOW
        rebuilt.append('%s  \u00b7  updated %s' % (title, ts))
        rebuilt.append(b)
    out = '\n'.join(rebuilt)
    if not out.endswith('\n'):
        out += '\n'

    if out != old:
        open(NS, 'w', encoding='utf-8').write(out)
        print('refreshed doc/Next-Steps.md')
    else:
        print('doc/Next-Steps.md already current')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Refresh doc/Next-Steps.md from git truth. Idempotent; safe to run every merge.

Three mechanical things:
  1. Regenerate the block between the LIVE-WORKTREES markers from
     build_status.inflight() — the single source of branch state.
  2. Flip `WP-NN` to `WP-NN`+check on the workstream chain lines (the indented
     arrow lines) for every package the plan marks Delivered. Only chain lines
     are touched, so prose is never mangled.
  3. Stamp each `## ` section header with `  ·  updated YYYY-MM-DD HH:MM`, moving
     the time forward only when that section's body changed this run.

All state comes from bin/build_status.py; this file only edits Next-Steps.md.
"""
import os, re, sys, datetime

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_status

ROOT  = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# The dashboard is a gitignored, generated file written into the MAIN checkout
# (what the user opens). It is never committed -- regenerating it each run is the
# heartbeat, and there is nothing to commit.
NS    = os.path.join(build_status.REPO, 'doc', 'Next-Steps.md')
NOW   = datetime.datetime.now().strftime('%Y-%m-%d %H:%M')
CHECK = '\u2713'
STAMP = re.compile(r'\s*\u00b7\s*updated \d{4}-\d\d-\d\d \d\d:\d\d\s*$')


def worktree_block():
    rows = ['    %-22s %-46s %s' % (n, s, '(%s)' % wp if wp else '')
            for n, s, wp in build_status.inflight()]
    if not rows:
        rows = ['    (none in flight — the queue is drained or the worker is between packages)']
    begin = '<!-- LIVE-WORKTREES:BEGIN (regenerated by bin/refresh-next-steps.py — do not hand-edit) -->'
    return begin + '\n' + '\n'.join(rows) + '\n<!-- LIVE-WORKTREES:END -->'


def flip_checks(text, delivered):
    def one(line):
        if '\u25ba' not in line and '->' not in line:      # only chain lines
            return line
        def sub(m):
            wp = 'WP-' + m.group(1)
            return wp + CHECK if (wp in delivered and m.group(2) != CHECK) else m.group(0)
        return re.sub(r'WP-(\d+)(' + CHECK + r'?)', sub, line)
    return '\n'.join(one(l) for l in text.split('\n'))


def split_sections(text):
    lines = text.split('\n')
    pre, secs, i = [], [], 0
    while i < len(lines) and not lines[i].startswith('## '):
        pre.append(lines[i]); i += 1
    while i < len(lines):
        header, i = lines[i], i + 1
        body = []
        while i < len(lines) and not lines[i].startswith('## '):
            body.append(lines[i]); i += 1
        secs.append((header, '\n'.join(body)))
    return '\n'.join(pre), secs


def main():
    old = open(NS, encoding='utf-8', errors='replace').read()
    delivered = build_status.delivered_wps()

    _, old_secs = split_sections(old)
    old_map = {}
    for h, b in old_secs:
        title = STAMP.sub('', h)
        m = STAMP.search(h)
        old_map[title] = (b, re.search(r'updated (.*?)\s*$', m.group(0)).group(1) if m else None)

    new = re.sub(r'<!-- LIVE-WORKTREES:BEGIN.*?LIVE-WORKTREES:END -->',
                 lambda _: worktree_block(), old, flags=re.S)
    new = flip_checks(new, delivered)

    pre, new_secs = split_sections(new)
    rebuilt = [pre] if pre else []
    for h, b in new_secs:
        title = STAMP.sub('', h)
        old_b, old_ts = old_map.get(title, (None, None))
        if 'Live worktrees' in title:
            ts = NOW                       # the live section is live: always stamp now
        else:
            ts = NOW if (old_b is None or old_b != b) else (old_ts or NOW)
        rebuilt.append('%s  \u00b7  updated %s' % (title, ts))
        rebuilt.append(b)
    out = '\n'.join(rebuilt)
    if not out.endswith('\n'):
        out += '\n'

    if out != old:
        open(NS, 'w', encoding='utf-8').write(out)
        print('refreshed doc/Next-Steps.md')
    else:
        print('doc/Next-Steps.md already current')


if __name__ == '__main__':
    main()

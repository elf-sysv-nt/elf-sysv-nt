#!/usr/bin/env python3
"""Refresh the two status views over the governed set and the decision records.

Neither file is a governing document and neither is tracked. They are views,
regenerated the way doc/Next-Steps.md is, and they exist because the two
questions they answer had no single place to be asked (proposal 0006):

  doc/status/provisional.md   which in-force records still await ratification,
                              with the ladder tier each names, so the backlog
                              is one screen instead of seventy-six files.
  doc/status/not-verified.md  every claim currently load-bearing that nobody
                              has measured, gathered from the Not verified
                              section of each governed document and each
                              in-force record, with its source.

Nothing here is stamped with a time. Two runs on one tree produce
byte-identical output, which is what makes this safe to run from a merge.

Usage:
  refresh-status-reports.py [-C DIR] [-q]
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Written into the main checkout, not the worktree a session happens to run
# from: these are the files the operator opens, and the operator opens one tree.
REPO = re.split(r'/a/wt/', ROOT.replace('\\', '/'))[0]

GOVERNED = ('doc/design/Requirements.md', 'doc/design/Architecture.md',
            'doc/design/ABI-Boundary.md', 'doc/design/Symbol-Resolution.md',
            'doc/design/Address-Space.md', 'doc/design/Runtime-Crossing.md',
            'doc/design/Verification-Plan.md', 'doc/design/glibc-reuse.md',
            'doc/design/target-definition.md', 'doc/design/licensing.md', 'AGENTS.md')

INDEX_ROW = re.compile(r'^\|\s*\[(\d{4})\]\(([^)]+)\)\s*\|')
TIER = re.compile(r'\b[Tt]ier (\d)\b')
HEADING = re.compile(r'^#+\s+(.*?)\s*#*\s*$')


def read(path):
    return open(path, encoding='utf-8', errors='replace').read()


def records(repo):
    """(number, filename, decision text, status cell) per index row, in order."""
    idx = os.path.join(repo, 'doc', 'design', 'decisions', 'index.md')
    out = []
    if not os.path.isfile(idx):
        return out
    for line in read(idx).split('\n'):
        m = INDEX_ROW.match(line)
        if not m:
            continue
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        decision = cells[1] if len(cells) > 1 else ''
        status = cells[2] if len(cells) > 2 else ''
        out.append((m.group(1), m.group(2), decision, status))
    return out


def in_force(status):
    return 'superseded by' not in status


def section(text, name):
    """The body of the first heading whose text is `name`, as a list of
    paragraphs. Returns [] when the document has no such heading."""
    lines, body, taking = text.split('\n'), [], False
    for line in lines:
        m = HEADING.match(line)
        if m:
            if taking:
                break
            taking = m.group(1).strip().lower() == name.lower()
            continue
        if taking:
            body.append(line)
    paras, cur = [], []
    for line in body:
        if line.strip():
            cur.append(line.strip())
        elif cur:
            paras.append(' '.join(cur)); cur = []
    if cur:
        paras.append(' '.join(cur))
    return paras


def provisional_report(repo):
    out = ['# Provisional records',
           '',
           'In-force decision records the operator has not ratified, with the',
           'ladder tier each names where it names one. Generated by',
           '`bin/refresh-status-reports.py`; not tracked, and not a governing',
           'document. Ratification is cheap by design: one sweep record settles',
           'many, in the shape DR-0036 already used.',
           '']
    rows = [r for r in records(repo)
            if in_force(r[3]) and 'provisional' in r[3].lower()]
    if not rows:
        out.append('None. Every in-force record is ratified.')
        out.append('')
        return '\n'.join(out)
    for num, fname, decision, status in rows:
        path = os.path.join(repo, 'doc', 'design', 'decisions', fname)
        tier = 'no tier named'
        if os.path.isfile(path):
            m = TIER.search(read(path))
            if m:
                tier = 'tier ' + m.group(1)
        out.append('- DR-%s (%s) — %s  [%s]' % (num, tier, decision, status))
    out.append('')
    out.append('%d of %d in-force records await ratification.'
               % (len(rows), len([r for r in records(repo) if in_force(r[3])])))
    out.append('')
    return '\n'.join(out)


def not_verified_report(repo):
    out = ['# Not verified',
           '',
           'Every claim under a Not verified heading in the governed set and in',
           'the in-force decision records, with its source. This is the page the',
           'convention in `AGENTS.md` has always implied and the tree has never',
           'had: what the design currently rests on and nobody has measured.',
           'Generated by `bin/refresh-status-reports.py`; not tracked.',
           '']
    total = 0

    out.append('## From the governed documents')
    out.append('')
    for rel in GOVERNED:
        p = os.path.join(repo, rel)
        if not os.path.isfile(p):
            continue
        paras = section(read(p), 'Not verified')
        if not paras:
            continue
        out.append('### %s' % rel)
        out.append('')
        for para in paras:
            out.append('- %s' % para)
            total += 1
        out.append('')

    out.append('## From the decision records')
    out.append('')
    for num, fname, decision, status in records(repo):
        if not in_force(status):
            continue
        p = os.path.join(repo, 'doc', 'design', 'decisions', fname)
        if not os.path.isfile(p):
            continue
        paras = section(read(p), 'Not verified')
        if not paras:
            continue
        out.append('### DR-%s — %s' % (num, decision))
        out.append('')
        for para in paras:
            out.append('- %s' % para)
            total += 1
        out.append('')

    out.insert(8, '%d unverified claim(s).' % total)
    out.insert(9, '')
    return '\n'.join(out)


def write(path, text, quiet):
    old = read(path) if os.path.isfile(path) else None
    if old == text:
        if not quiet:
            print('refresh-status-reports: %s unchanged' % os.path.basename(path))
        return
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    if not quiet:
        print('refresh-status-reports: wrote %s' % os.path.basename(path))


def main(argv):
    repo, quiet = REPO, False
    i = 0
    while i < len(argv):
        a = argv[i]
        if a in ('-h', '--help'):
            print(__doc__.strip()); return 0
        elif a in ('-q', '--quiet'):
            quiet = True
        elif a in ('-C', '--directory'):
            i += 1; repo = argv[i]
        elif a.startswith('--directory='):
            repo = a.split('=', 1)[1]
        else:
            sys.stderr.write('refresh-status-reports: unknown option %s\n' % a)
            return 2
        i += 1

    d = os.path.join(repo, 'doc', 'status')
    if not os.path.isdir(d):
        sys.stderr.write('refresh-status-reports: no %s\n' % d); return 1
    write(os.path.join(d, 'provisional.md'), provisional_report(repo), quiet)
    write(os.path.join(d, 'not-verified.md'), not_verified_report(repo), quiet)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
